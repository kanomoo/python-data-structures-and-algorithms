function processDir(dir) {
  const files = fs.readdirSync(dir);
  for (const f of files) {
    if (!f.endsWith('.md')) continue;
    const match = f.match(/^(\d+\.\d+)/);
    if (!match) continue;
    const prefix = match[1];
    const qa = qaData[prefix];
    if (!qa) continue;

    const filePath = path.join(dir, f);
    let content = fs.readFileSync(filePath, 'utf8').replace(/\r\n/g, '\n');

    if (content.includes('Official Exam Q&A Solutions Sheet')) {
      console.log(`Already has QA section: ${f}`);
      continue;
    }

    // Find first ---
    const dashIdx = content.indexOf('\n---\n');
    if (dashIdx >= 0) {
      const insertionPoint = dashIdx + 5;
      content = content.slice(0, insertionPoint) + '\n' + qa + content.slice(insertionPoint);
    } else {
      content = qa + '\n' + content;
    }

    fs.writeFileSync(filePath, content, 'utf8');
    console.log(`Injected QA section into: ${f}`);
  }
}

